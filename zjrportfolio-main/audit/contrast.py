def lum(h):
    h = h.lstrip('#')
    r, g, b = [int(h[i:i+2], 16) / 255 for i in (0, 2, 4)]

    def f(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def cr(a, b):
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


pairs = [
    ('#737373', '#141414'), ('#737373', '#0A0A0A'), ('#525252', '#141414'),
    ('#525252', '#101010'), ('#A3A3A3', '#141414'), ('#A3A3A3', '#0A0A0A'),
    ('#C9C9C9', '#141414'), ('#FFFFFF', '#141414'), ('#9EFF00', '#000000'),
    ('#000000', '#9EFF00'), ('#737373', '#1A1A1A'), ('#525252', '#1A1A1A'),
    ('#A3A3A3', '#000000'), ('#737373', '#000000'),
]
for a, b in pairs:
    print(f'{a} on {b}: {cr(a, b):.2f}:1')
